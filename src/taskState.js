import { reactive } from 'vue'

/**
 * 各模块「后台任务」的跨页可见状态（2026-10-22）。
 * 与 imggenState.js 同款：任务本身跑在组件实例里（视图用 v-show 常驻，切菜单不销毁），
 * 侧栏只想知道「哪个模块还有任务在跑」→ 这里放最小只读状态，业务逻辑一律留在组件里。
 * 组件用 watch 把 busy 镜像进来，侧栏据此在对应菜单旁显示闪烁小点（.nav-dot）。
 *
 * 🔴 为什么分镜（shots）也要：用户反馈「分镜批量生成时切到别的菜单，任务就断了」——
 *    除了让 dash 视图 v-show 常驻（不销毁组件），还要让「还在跑」这件事能被侧栏感知，
 *    切走后用户在侧栏一看小点就知道任务没停。
 */
export const taskState = reactive({
  shots: { busy: false, text: '' },   // 分镜：批量生成提示词 / 批量生成视频 / 单镜生成
  lib:   { busy: false, text: '' }    // 项目角色场景库：批量生成提示词 / 批量生成图片
})
